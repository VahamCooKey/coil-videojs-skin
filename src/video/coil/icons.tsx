/**
 * COIL pixel icons: 12 x 12 bitmaps drawn as crisp SVG rects in currentColor.
 * Same export names as `@videojs/react/icons/scaffold`, so the skin's buttons only change their import path.
 * Icons without a pixel version are re-exported from the scaffold set.
 */

import type { SVGProps } from 'react';

export {
  AirPlayEnterIcon,
  AirPlayExitIcon,
  CastEnterIcon,
  CastExitIcon,
  SeekIcon,
  SpinnerIcon,
} from '@videojs/react/icons/scaffold';

type IconProps = SVGProps<SVGSVGElement>;

function pixelIcon(rows: string[]) {
  // Merge horizontal runs so each row is a few rects, not one per pixel.
  const rects: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= row.length; x++) {
      const on = row[x] === '#';
      if (on && start < 0) start = x;
      if (!on && start >= 0) {
        rects.push({ x: start, y, w: x - start });
        start = -1;
      }
    }
  });

  return function PixelIcon(props: IconProps) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 12 12"
        width="24"
        height="24"
        fill="currentColor"
        shapeRendering="crispEdges"
        aria-hidden="true"
        focusable="false"
        {...props}
      >
        {rects.map((r) => (
          <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} />
        ))}
      </svg>
    );
  };
}

